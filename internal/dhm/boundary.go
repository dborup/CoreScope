// #692 — the coverage gate. The DHM WCS answers 0.0, not nodata, outside
// Denmark. The decoder honours GDAL_NODATA, yet the zeros reached the
// profile as elevations, so the GeoTIFFs carry no tag that marks them, and
// WCS 1.0.0 GetCoverage has no request option for a nodata fill. On the
// sea the zero is the true height, Danish sea or not. On foreign land it
// is wrong: the RasterExtent rectangle includes Skåne, Schleswig and
// Rügen, which would read as sea level. The terrain profile therefore
// counts a sample as covered inside RasterExtent unless it lies on this
// polygon: Swedish, German, Polish and Norwegian land in the extent.
//
// foreign_land.txt is generated by scripts/gen-dhm-foreign-land.py from
// Natural Earth 1:10m Admin 0 Countries v5.1.1 and Minor Islands v4.1.0
// (public domain, no attribution required; Minor Islands adds Ven): that
// land clipped to the extent plus 2 km, simplified with a 150 m
// Douglas-Peucker tolerance, minus Danish land. The source itself is
// accurate to a few hundred metres along the coast, against the
// kilometres of land a path into a neighbour crosses. Coordinates are
// integer EPSG:25832 metres, one "ring" line per ring; the rings are
// tested even-odd, so a hole is just another ring.

//go:embed foreign_land.txt
var foreignLandText string

// boundaryCellM is the edge of an index cell. A cell that no polygon edge
// touches is wholly inside or outside and answers without a
// point-in-polygon test. For foreign_land.txt the grid is 444 × 361 cells
// (157 KB), about 2 % of them edge cells.
const boundaryCellM = 1000

const (
	cellOut uint8 = iota
	cellIn
	cellEdge
)

// boundarySeg is one polygon edge, from (e0, n0) to (e1, n1).
type boundarySeg struct{ e0, n0, e1, n1 float64 }

// boundary is a parsed polygon and its index: a grid of boundaryCellM
// cells over the polygon's bbox, and per grid row the edges whose
// northing range meets that row.
type boundary struct {
	minE, minN, maxE, maxN float64
	nx, ny                 int
	cells                  []uint8
	rows                   [][]int32
	segs                   []boundarySeg
}

var foreignLand = sync.OnceValue(func() *boundary {
	b, err := parseBoundary(foreignLandText)
	if err != nil {
		panic("dhm: embedded foreign_land.txt: " + err.Error())
	}
	return b
})

// Covers reports whether DHM has a real elevation at the EPSG:25832 point
// (e, n): inside RasterExtent and not on foreign land (its coast
// included). NaN and ±Inf are not covered.
func Covers(e, n float64) bool {
	ext := RasterExtent
	// Written so NaN fails: every comparison with NaN is false. The
	// extent check is first: it is cheaper.
	return e >= ext[0] && e <= ext[2] && n >= ext[1] && n <= ext[3] && !foreignLand().has(e, n)
}

// has reports whether (e, n) is inside the polygon, boundary included.
func (b *boundary) has(e, n float64) bool {
	if !(e >= b.minE && e <= b.maxE && n >= b.minN && n <= b.maxN) {
		return false
	}
	cx := min(int((e-b.minE)/boundaryCellM), b.nx-1)
	cy := min(int((n-b.minN)/boundaryCellM), b.ny-1)
	switch b.cells[cy*b.nx+cx] {
	case cellIn:
		return true
	case cellOut:
		return false
	}
	return b.contains(e, n, b.rows[cy])
}

// contains is the even-odd test of (e, n) against the edges segs, which
// must include every edge whose northing range contains n. A point on an
// edge is inside.
func (b *boundary) contains(e, n float64, segs []int32) bool {
	in := false
	for _, i := range segs {
		s := &b.segs[i]
		if onSegment(s, e, n) {
			return true
		}
		if (s.n0 > n) != (s.n1 > n) && e < s.e0+(n-s.n0)*(s.e1-s.e0)/(s.n1-s.n0) {
			in = !in
		}
	}
	return in
}

// onSegment reports whether (e, n) is within a millimetre of s.
func onSegment(s *boundarySeg, e, n float64) bool {
	const eps = 1e-3
	if e < math.Min(s.e0, s.e1)-eps || e > math.Max(s.e0, s.e1)+eps ||
		n < math.Min(s.n0, s.n1)-eps || n > math.Max(s.n0, s.n1)+eps {
		return false
	}
	de, dn := s.e1-s.e0, s.n1-s.n0
	return math.Abs(de*(n-s.n0)-dn*(e-s.e0)) <= eps*math.Hypot(de, dn)
}

var errBoundary = errors.New("malformed boundary")

// parseBoundary reads "ring E,N E,N E,N ..." lines ("#" lines are
// comments) and builds the index.
func parseBoundary(text string) (*boundary, error) {
	b := &boundary{minE: math.Inf(1), minN: math.Inf(1), maxE: math.Inf(-1), maxN: math.Inf(-1)}
	for _, line := range strings.Split(text, "\n") {
		f := strings.Fields(line)
		if len(f) == 0 || strings.HasPrefix(f[0], "#") {
			continue
		}
		if f[0] != "ring" || len(f) < 4 {
			return nil, errBoundary
		}
		ring := make([][2]float64, len(f)-1)
		for i, pt := range f[1:] {
			es, ns, ok := strings.Cut(pt, ",")
			e, err1 := strconv.ParseFloat(es, 64)
			n, err2 := strconv.ParseFloat(ns, 64)
			if !ok || err1 != nil || err2 != nil || math.IsNaN(e) || math.IsNaN(n) || math.IsInf(e, 0) || math.IsInf(n, 0) {
				return nil, errBoundary
			}
			ring[i] = [2]float64{e, n}
			b.minE, b.maxE = math.Min(b.minE, e), math.Max(b.maxE, e)
			b.minN, b.maxN = math.Min(b.minN, n), math.Max(b.maxN, n)
		}
		for i, p := range ring {
			q := ring[(i+1)%len(ring)]
			b.segs = append(b.segs, boundarySeg{p[0], p[1], q[0], q[1]})
		}
	}
	if len(b.segs) == 0 {
		return nil, errBoundary
	}
	b.nx = int(math.Ceil((b.maxE-b.minE)/boundaryCellM)) + 1
	b.ny = int(math.Ceil((b.maxN-b.minN)/boundaryCellM)) + 1
	b.rows = make([][]int32, b.ny)
	b.cells = make([]uint8, b.nx*b.ny)
	// Every cell an edge's bbox touches is an edge cell: conservative, so
	// a non-edge cell holds no boundary point and has one answer.
	for i, s := range b.segs {
		cx0, cx1 := b.cellRange(math.Min(s.e0, s.e1), math.Max(s.e0, s.e1), b.minE, b.nx)
		cy0, cy1 := b.cellRange(math.Min(s.n0, s.n1), math.Max(s.n0, s.n1), b.minN, b.ny)
		for cy := cy0; cy <= cy1; cy++ {
			b.rows[cy] = append(b.rows[cy], int32(i))
			for cx := cx0; cx <= cx1; cx++ {
				b.cells[cy*b.nx+cx] = cellEdge
			}
		}
	}
	for cy := 0; cy < b.ny; cy++ {
		for cx := 0; cx < b.nx; cx++ {
			c := &b.cells[cy*b.nx+cx]
			if *c == cellEdge {
				continue
			}
			e := b.minE + (float64(cx)+0.5)*boundaryCellM
			n := b.minN + (float64(cy)+0.5)*boundaryCellM
			if b.contains(e, n, b.rows[cy]) {
				*c = cellIn
			}
		}
	}
	return b, nil
}

// cellRange is the cells [c0, c1] of a grid axis starting at origin with
// n cells that the interval [lo, hi] touches, widened by the onSegment
// tolerance so a point on a cell edge finds its segment.
func (b *boundary) cellRange(lo, hi, origin float64, n int) (int, int) {
	const eps = 1e-3
	c0 := max(0, int(math.Floor((lo-eps-origin)/boundaryCellM)))
	c1 := min(n-1, int(math.Floor((hi+eps-origin)/boundaryCellM)))
	return c0, c1
}
