#!/usr/bin/env python3
"""Generate internal/dhm/testdata/dk_border_739.txt (#739 M1).

Test points for the foreign-land gate, taken from Klimadatastyrelsen's
Topografisk Landpolygon (layers landpolygon_10 and havpolygon_10), so CI
can check the embedded polygon against the precise Danish border without
the 189 MB GeoPackage. Every point lies OFFSET_M from the border, on the
side its tag names, and is checked to be so:

  dk   Danish land, OFFSET_M inside the Danish-German land border;
  de   German land, OFFSET_M outside Danish territory, same places;
  sea  Danish sea, OFFSET_M inside Denmark's outer sea limit, wherever
       that limit is within NEAR_M of Natural Earth foreign land (the
       only places the gate's 1250 m buffer can reach Danish sea).

The land border is the part of the Danish land outline that no Danish sea
touches (the coast does touch it) south of BORDER_MAX_N. Points are
STEP_M apart along each line, in EPSG:25832 integer metres.

Dev-only, same pinned venv as scripts/gen-dhm-foreign-land.py:
  python3 -I scripts/gen-dhm-border-fixture.py ne_10m_admin_0_countries.shp \\
      landpolygon.gpkg > internal/dhm/testdata/dk_border_739.txt
"""
import sqlite3
import sys

import numpy as np
import shapefile
import shapely
from pyproj import Transformer
from shapely.geometry import shape
from shapely.ops import unary_union

RASTER_EXTENT = (440000, 6048000, 894000, 6404000)  # internal/dhm/wcs.go
OFFSET_M = 50.0
STEP_M = 250.0
NEAR_M = 2500.0
BORDER_MAX_N = 6110000.0  # about 55.1 N: the land border is at 54.8-54.91 N
FOREIGN = ("SWE", "DEU", "POL", "NOR")

to_utm = Transformer.from_crs("EPSG:4326", "EPSG:25832", always_xy=True).transform


def gpkg(path, table):
    db = sqlite3.connect("file:%s?mode=ro" % path, uri=True)
    out = []
    for (b,) in db.execute("SELECT geometri FROM %s ORDER BY ogc_fid" % table):
        env = {0: 0, 1: 32, 2: 48, 3: 48, 4: 64}[(b[3] >> 1) & 7]
        out.append(shapely.from_wkb(bytes(b[8 + env:])))
    return unary_union(out)


def lines(g):
    g = shapely.line_merge(g) if not g.is_empty else g
    return [l for l in getattr(g, "geoms", [g]) if isinstance(l, shapely.LineString) and l.length > 0]


def samples(line_geoms, inside, outside, tag_in, tag_out, keep=lambda p: True):
    rows = []
    for l in line_geoms:
        for k in range(int(l.length // STEP_M) + 1):
            s = min(k * STEP_M + STEP_M / 2, l.length)
            p, q = l.interpolate(max(s - 1, 0)), l.interpolate(min(s + 1, l.length))
            c = l.interpolate(s)
            dx, dy = q.x - p.x, q.y - p.y
            d = (dx * dx + dy * dy) ** 0.5
            if d == 0 or not keep(c):
                continue
            nx, ny = -dy / d * OFFSET_M, dx / d * OFFSET_M
            a, b = shapely.Point(c.x + nx, c.y + ny), shapely.Point(c.x - nx, c.y - ny)
            if not inside.contains(a):
                a, b = b, a
            # Both points must be on their side and OFFSET_M clear of the
            # whole border (not only of this line), or a bend nearby has
            # put them somewhere else: drop the pair.
            pa = (round(a.x), round(a.y))
            pb = (round(b.x), round(b.y))
            A, B = shapely.Point(pa), shapely.Point(pb)
            if not (inside.contains(A) and inside.boundary.distance(A) >= OFFSET_M - 2):
                continue
            rows.append((tag_in, pa))
            if tag_out and outside.contains(B) and inside.distance(B) >= OFFSET_M - 2:
                rows.append((tag_out, pb))
    return rows


def main(countries, gpkg_path):
    sf = shapefile.Reader(countries)
    fo = unary_union([shape(sr.shape.__geo_interface__) for sr in sf.iterShapeRecords()
                      if sr.record["ADM0_A3"] in FOREIGN])
    fo = shapely.transform(fo, lambda c: np.column_stack(to_utm(c[:, 0], c[:, 1])))
    x0, y0, x1, y1 = RASTER_EXTENT
    box = shapely.box(x0, y0, x1, y1)
    land = gpkg(gpkg_path, "landpolygon_10")
    sea = gpkg(gpkg_path, "havpolygon_10")
    dk = unary_union([land, sea])
    world = box.buffer(50000)
    south = shapely.box(x0, y0, x1, BORDER_MAX_N)
    border = land.boundary.intersection(south).difference(sea.buffer(1.0))
    rows = samples(lines(border), land, world.difference(dk), "dk", "de")
    near = fo.buffer(NEAR_M)
    outer = sea.boundary.intersection(box).difference(land.buffer(1.0)).intersection(near)
    rows += samples(lines(outer), sea, None, "sea", None)
    print("# #739 M1: points OFFSET_M=%gm off the Danish border, EPSG:25832 metres;" % OFFSET_M)
    print("# generated by scripts/gen-dhm-border-fixture.py from Topografisk Landpolygon")
    print("# (landpolygon_10, havpolygon_10). Indeholder data fra Klimadatastyrelsen,")
    print("# Topografisk Landpolygon, november 2026.")
    for tag, (e, n) in rows:
        print("%s %d %d" % (tag, e, n))
    print("dk=%d de=%d sea=%d" % tuple(sum(r[0] == t for r in rows) for t in ("dk", "de", "sea")), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
