#!/usr/bin/env python3
"""Generate internal/dhm/denmark_boundary.txt (#692).

The DHM WCS returns 0.0, not nodata, outside Danish coverage, so the
terrain profile gates every sample with this polygon: Danish land plus
Danish waters, in EPSG:25832 metres.

Source: Natural Earth 1:10m Cultural Vectors, Admin 0 - Countries, v5.1.1
(https://www.naturalearthdata.com/, public domain; no attribution required).

Construction, on a RES-metre grid in EPSG:25832:
  * Danish land (ADMIN == "Denmark") and foreign land (Sweden, Germany,
    Poland, Norway) are rasterised.
  * A cell is inside when it is closer to Danish land than to any foreign
    land (the equidistance line, which on land is the land border itself)
    and within TERRITORIAL_M (12 nautical miles) of Danish land.
  * The cells are polygonised and simplified (Douglas-Peucker, tolerance
    SIMPLIFY_M, topology preserved); parts and holes smaller than
    MIN_AREA_M2 (rasterisation artefacts) are dropped.
This approximates the territorial sea (normal baselines only, not Denmark's
straight baselines) and the maritime boundaries with Sweden, Germany and
Poland, which follow the median line closely.

Dev-only tool, not part of the build:
  uv venv && uv pip install shapely scipy pyproj numpy pyshp
  python3 scripts/gen-dk-boundary.py ne_10m_admin_0_countries.shp \
      > internal/dhm/denmark_boundary.txt
"""
import sys

import numpy as np
import shapefile
from pyproj import Transformer
from scipy import ndimage
import shapely
from shapely.geometry import shape
from shapely.ops import unary_union

RES = 100.0
TERRITORIAL_M = 12 * 1852.0
SIMPLIFY_M = 150.0  # 1.5 cells: removes the raster staircase
MIN_AREA_M2 = 1e6
FOREIGN = ("Sweden", "Germany", "Poland", "Norway")

to_utm = Transformer.from_crs("EPSG:4326", "EPSG:25832", always_xy=True).transform


def land(sf, names):
    geoms = [shape(sr.shape.__geo_interface__) for sr in sf.iterShapeRecords()
             if sr.record["ADMIN"] in names]
    return shapely.transform(unary_union(geoms), lambda c: np.column_stack(to_utm(c[:, 0], c[:, 1])))


def main(path):
    sf = shapefile.Reader(path)
    dk = land(sf, ("Denmark",))
    fo = land(sf, FOREIGN)
    pad = TERRITORIAL_M + 5 * RES
    minx, miny, maxx, maxy = dk.bounds
    x0, y0 = np.floor((minx - pad) / RES) * RES, np.floor((miny - pad) / RES) * RES
    nx = int(np.ceil((maxx + pad - x0) / RES))
    ny = int(np.ceil((maxy + pad - y0) / RES))
    xs = x0 + (np.arange(nx) + 0.5) * RES
    ys = y0 + (np.arange(ny) + 0.5) * RES
    gx, gy = np.meshgrid(xs, ys)
    shapely.prepare(dk)
    shapely.prepare(fo)
    in_dk = shapely.contains_xy(dk, gx, gy)
    in_fo = shapely.contains_xy(fo, gx, gy) & ~in_dk
    d_dk = ndimage.distance_transform_edt(~in_dk) * RES
    d_fo = ndimage.distance_transform_edt(~in_fo) * RES
    inside = (d_dk < d_fo) & (d_dk <= TERRITORIAL_M)

    boxes = []
    for j in range(ny):
        row = np.concatenate(([False], inside[j], [False]))
        edges = np.flatnonzero(row[1:] != row[:-1])
        for a, b in zip(edges[::2], edges[1::2]):
            boxes.append(shapely.box(x0 + a * RES, y0 + j * RES, x0 + b * RES, y0 + (j + 1) * RES))
    region = shapely.union_all(boxes).simplify(SIMPLIFY_M, preserve_topology=True)
    parts = [shapely.Polygon(p.exterior, [h for h in p.interiors if shapely.Polygon(h).area >= MIN_AREA_M2])
             for p in getattr(region, "geoms", [region]) if p.area >= MIN_AREA_M2]
    region = shapely.MultiPolygon(parts)
    assert region.is_valid
    print("# Danish land + waters, EPSG:25832 metres; generated by scripts/gen-dk-boundary.py")
    print("# Source: Natural Earth 10m Admin 0 Countries v5.1.1 (public domain).")
    print("# res=%gm territorial=%gm simplify=%gm" % (RES, TERRITORIAL_M, SIMPLIFY_M))
    nv = 0
    for p in getattr(region, "geoms", [region]):
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            nv += len(pts)
            print("ring " + " ".join("%d,%d" % (round(x), round(y)) for x, y in pts))
    print("polygons=%d vertices=%d" % (len(region.geoms), nv), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
