#!/usr/bin/env python3
"""Generate internal/copdem/tiles.txt (#738 M1).

The Copernicus DEM GLO-30 bucket on AWS Open Data (copernicus-dem-30m)
holds one Cloud-Optimized GeoTIFF per 1 x 1 degree tile. A tile that is
entirely sea does not exist; its readme says to assume height values
equal to zero there. The bucket lists every existing tile in
tileList.txt, one name per line:

    Copernicus_DSM_COG_10_N55_00_E012_00_DEM

The foreign fill needs that list to tell the sea (no tile: 0 m, no
request) from a tile it must fetch (a 404 for a listed tile is an error,
never 0 m). This script keeps the tiles of REGION and writes them as
"N55E012" lines, sorted, with a header naming the source and its MD5.

REGION: every point of a terrain profile is within maxPathKm (at most
80 km) of a sample DHM covers, and the fill only runs for a profile with
at least one (internal/dhm RasterExtent, about 54.57-57.78 N and
8.0-15.6 E). 80 km reaches about 53.85-58.50 N and, at those latitudes,
6.6-16.9 E, so latitudes 53-58 and longitudes 6-16 (south-west corners)
hold every tile a profile can touch, with margin. The fill treats any
tile outside REGION as unknown (no value), never as sea.

Stdlib only. Usage:

    curl -sSf -o tileList.txt https://copernicus-dem-30m.s3.amazonaws.com/tileList.txt
    python3 scripts/gen-copdem-tiles.py tileList.txt > internal/copdem/tiles.txt

Then update tilesSHA256 in internal/copdem/tiles_test.go.
"""

import hashlib
import re
import sys

REGION_LAT = range(53, 59)  # south edges, degrees north
REGION_LON = range(6, 17)  # west edges, degrees east
SOURCE = "https://copernicus-dem-30m.s3.amazonaws.com/tileList.txt"
NAME = re.compile(r"^Copernicus_DSM_COG_10_([NS])(\d{2})_00_([EW])(\d{3})_00_DEM$")


def main(path):
    raw = open(path, "rb").read()
    tiles = set()
    total = 0
    for line in raw.decode("ascii").splitlines():
        line = line.strip()
        if not line:
            continue
        m = NAME.match(line)
        if not m:
            sys.exit("unexpected line in tileList.txt: %r" % line)
        total += 1
        lat = int(m.group(2)) * (1 if m.group(1) == "N" else -1)
        lon = int(m.group(4)) * (1 if m.group(3) == "E" else -1)
        if lat in REGION_LAT and lon in REGION_LON:
            tiles.add((lat, lon))
    out = sys.stdout
    out.write("# Copernicus DEM GLO-30 tiles that exist in the AWS bucket, for the\n")
    out.write("# #738 foreign fill. Generated by scripts/gen-copdem-tiles.py; do not edit.\n")
    out.write("# source: %s\n" % SOURCE)
    out.write("# source md5: %s, %d tiles listed\n" % (hashlib.md5(raw).hexdigest(), total))
    out.write("# region: south edges N%02d-N%02d, west edges E%03d-E%03d (%d tiles, %d exist)\n" % (
        REGION_LAT[0], REGION_LAT[-1], REGION_LON[0], REGION_LON[-1],
        len(REGION_LAT) * len(REGION_LON), len(tiles)))
    for lat, lon in sorted(tiles):
        out.write("N%02dE%03d\n" % (lat, lon))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
